#!/usr/bin/env bash
# gen-static-libs.sh OUT NAME:LIST... writes the C table of statically linked
# extension libraries that compat/src/dl.c searches. Each LIST is the object
# list file written by objs.mk. The script finds the exported SQL-callable
# functions through the pg_finfo_ convention of PG_FUNCTION_INFO_V1.
set -euo pipefail
export LC_ALL=C
out=$1
shift
NM=/opt/wasi-sdk/bin/llvm-nm
{
	echo '/* Generated by build/gen-static-libs.sh. */'
	echo '#include "postgres.h"'
	echo '#include "fmgr.h"'
	echo '#include "pgmem_static_libs.h"'
	for lib in "$@"; do
		name=${lib%%:*}
		list=${lib#*:}
		syms=$("$NM" --defined-only -g $(cat "$list") | awk '$2 == "T" {print $3}' | sort -u)
		funcs=$(sed -n 's/^pg_finfo_//p' <<<"$syms")
		echo
		echo "extern const Pg_magic_struct *Pg_magic_func_$name(void);"
		if grep -qx "_PG_init_$name" <<<"$syms"; then
			echo "extern void _PG_init_$name(void);"
		fi
		for f in $funcs; do
			echo "extern const Pg_finfo_record *pg_finfo_$f(void);"
			echo "extern Datum $f(PG_FUNCTION_ARGS);"
		done
		echo "static const struct pgmem_static_symbol ${name}_symbols[] = {"
		echo "	{\"Pg_magic_func\", (void *) Pg_magic_func_$name},"
		if grep -qx "_PG_init_$name" <<<"$syms"; then
			echo "	{\"_PG_init\", (void *) _PG_init_$name},"
		fi
		for f in $funcs; do
			echo "	{\"pg_finfo_$f\", (void *) pg_finfo_$f},"
			echo "	{\"$f\", (void *) $f},"
		done
		echo "	{NULL, NULL}"
		echo "};"
	done
	echo
	echo "const struct pgmem_static_library pgmem_static_libraries[] = {"
	for lib in "$@"; do
		name=${lib%%:*}
		echo "	{\"$name\", ${name}_symbols},"
	done
	echo "	{NULL, NULL}"
	echo "};"
} >"$out"
